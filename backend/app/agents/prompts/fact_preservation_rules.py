"""
医学事实保真禁令（P0-2 / R3）

共享于：
  - 生成层 prompt（task_prompts / system 等）→ 使用 ``FACT_PRESERVATION_RULES``（描述式）
  - 改写层 prompt（deai_rewriter）→ 使用 ``REWRITE_FACT_RULES``（命令式）+ 示例

设计理念（同决策附录 A.8 / R3）：
  同一组规则在两个场景的语气不同：
  - 生成是从无到有，讲"要做什么"更有效
  - 改写是对照原文，讲"不能动什么"更有效
  违规示例 / 合法示例只放改写层，生成层不需要这些反例。

任何修改这里的常量都需要：
  1. 同步更新 docs/AIGC治理可执行方案_v1.1.md 附录 A
  2. 跑改写器单元测试 + 一次完整生成回归
"""

# ────────────────────────────────────────────
# 生成层：描述式（讲"要做什么"）
# ────────────────────────────────────────────

FACT_PRESERVATION_RULES = """\
【信息保真要求】（违反任何一条都视为不合格）

1. 不得出现没有事实依据的具体数字、百分比、年份、人数、剂量
2. 不得出现没有事实依据的药物名、机构名、研究名、人名
3. 涉及研究对象时必须准确（小鼠 vs 人体、儿童 vs 成人、健康人 vs 患者）
4. 不得改变结论方向（避免把"有效"写成"可能有效"或反之）
5. 不得改变限定词强度（避免"可能"→"确定"、"少数"→"部分"等隐式扩大）
6. 引用标注必须保留：[文献N]、[N]、[共识]、[推断: ...]、[[待补充: ...]]
7. 你的任务是写好句式、节奏、连接词，不是补充原资料没有的信息"""


# ────────────────────────────────────────────
# 改写层：命令式（讲"不能动什么"）
# ────────────────────────────────────────────

REWRITE_FACT_RULES = """\
【信息保真禁令】（对照原文，违反任何一条都视为改写失败、自动回退到原文）

1. 禁止补充原文没有的具体数字、百分比、年份、人数、剂量
2. 禁止补充原文没有的药物名、机构名、研究名、人名
3. 禁止改变研究对象（小鼠 vs 人体、儿童 vs 成人、健康人 vs 患者）
4. 禁止改变结论方向（"有效"不能改成"可能有效"或反之）
5. 禁止改变限定词强度
   ✗ "可能有效" → "有效"
   ✗ "少数患者" → "部分患者"
   ✗ "罕见副作用" → "常见副作用"
   ✗ "建议" → "必须"
6. 禁止删除、增加或修改 [文献N]、[N]、[共识]、[推断: ...]、[[待补充: ...]] 标注
7. 你只改句式、节奏、连接词；不改任何信息"""


REWRITE_VIOLATION_EXAMPLES = """\
【违规改写示例】（系统会自动检测并回退）

违规 1：补充信息
  原文："研究表明该药物有效。"
  错误："2023 年的一项临床研究表明该药物有效。"
  原因：无中生有"2023 年"和"临床"

违规 2：补充药物名
  原文："临床上使用一种 β 受体阻滞剂控制心率。"
  错误："临床上使用美托洛尔控制心率。"
  原因：原文未指明具体药物，不得自行补充

违规 3：改变研究对象（医学灾难级）
  原文："小鼠实验显示该药物降低肿瘤体积 40%。"
  错误："临床研究显示该药物降低患者肿瘤体积 40%。"
  原因：把"小鼠"改成"临床患者"

违规 4：改变限定词
  原文："[推断: 可能与 X 相关]"
  错误："与 X 相关"
  原因：推断改成肯定，且删除标注

违规 5：补充精度
  原文："约 15% 的患者出现不良反应。"
  错误："15.3% 的患者出现不良反应。"
  原因："约 15%"不等于"15.3%"，精度被悄悄提升"""


REWRITE_LEGAL_EXAMPLES = """\
【合法改写示例】（句式变化、事实保留）

示例 1：句式重组
  原文："研究表明，该药物有效率约 75%。"
  改写："约 75% 的患者在该药物治疗下表现出疗效。"
  说明：句式重组，数字、修饰语、结论方向全部保留

示例 2：句序变化
  原文："小鼠实验 [文献1] 显示 5-10 mg/kg 剂量安全。"
  改写："在小鼠实验中 [文献1]，5-10 mg/kg 是安全剂量。"
  说明：句序变化，所有事实保留

示例 3：连接词替换
  原文："首先，糖尿病患者血糖波动大；其次，胰岛素剂量需个体化调整 [共识]。"
  改写："糖尿病患者血糖波动大，胰岛素剂量需要个体化调整 [共识]。"
  说明：拆掉"首先 / 其次"模板词，事实和标注完整保留"""


# ────────────────────────────────────────────
# 复合块（一次性把禁令 + 示例打到 prompt 末尾）
# ────────────────────────────────────────────

REWRITE_FACT_BLOCK = "\n\n".join([
    REWRITE_FACT_RULES,
    REWRITE_LEGAL_EXAMPLES,
    REWRITE_VIOLATION_EXAMPLES,
])
"""改写器 system / user prompt 末尾的完整块（禁令 + 合法示例 + 违规示例）。"""


